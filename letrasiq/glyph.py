"""Per-glyph source loading and validation."""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

from fontTools.agl import toUnicode

GlyphType = Literal["custom", "drawn"]

# Printable ASCII, the charset every font covers
ASCII_SYMBOLS: dict[str, str] = {
    "exclam": "!",
    "quotedbl": '"',
    "numbersign": "#",
    "dollar": "$",
    "percent": "%",
    "ampersand": "&",
    "quotesingle": "'",
    "parenleft": "(",
    "parenright": ")",
    "asterisk": "*",
    "plus": "+",
    "comma": ",",
    "hyphen": "-",
    "period": ".",
    "slash": "/",
    "colon": ":",
    "semicolon": ";",
    "less": "<",
    "equal": "=",
    "greater": ">",
    "question": "?",
    "at": "@",
    "bracketleft": "[",
    "backslash": "\\",
    "bracketright": "]",
    "asciicircum": "^",
    "underscore": "_",
    "grave": "`",
    "braceleft": "{",
    "bar": "|",
    "braceright": "}",
    "asciitilde": "~",
}

DIGIT_NAMES = {
    "0": "zero",
    "1": "one",
    "2": "two",
    "3": "three",
    "4": "four",
    "5": "five",
    "6": "six",
    "7": "seven",
    "8": "eight",
    "9": "nine",
}

ASCII_GLYPHS: tuple[str, ...] = (
    "space",
    *list("ABCDEFGHIJKLMNOPQRSTUVWXYZ"),
    *list("abcdefghijklmnopqrstuvwxyz"),
    *DIGIT_NAMES.values(),
    *ASCII_SYMBOLS,
)


@dataclass
class GlyphSource:
    """An outline on disk: ``drawn`` is generated by draw.py; ``custom`` is traced or imported."""

    name: str
    type: GlyphType
    path: str | None = None
    width: int | None = None
    anchors: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        data: dict[str, Any] = {"type": self.type, "path": self.path or ""}
        if self.width is not None:
            data["width"] = self.width
        if self.anchors:
            data["anchors"] = {k: list(v) for k, v in self.anchors.items()}
        return data

    def save(self, path: Path) -> None:
        path.write_text(json.dumps(self.to_dict(), indent=2) + "\n", encoding="utf-8")

    @classmethod
    def from_dict(cls, name: str, data: dict[str, Any]) -> GlyphSource:
        gtype = data.get("type", "custom")
        if gtype not in ("custom", "drawn"):
            raise ValueError(f"{name}: unsupported glyph type {gtype!r}")
        return cls(name=name, type=gtype, path=data.get("path", ""), width=data.get("width"), anchors=data.get("anchors", {}))

    @classmethod
    def load(cls, path: Path) -> GlyphSource:
        name = glyph_name_from_path(path)
        return cls.from_dict(name, json.loads(path.read_text(encoding="utf-8")))


def glyph_char(name: str) -> str | None:
    if len(name) == 1:
        return name
    # Alternates like zero.tf are reached through features, not typed directly.
    if "." in name:
        return None
    if name == "space":
        return " "
    if name in ASCII_SYMBOLS:
        return ASCII_SYMBOLS[name]
    for digit, gname in DIGIT_NAMES.items():
        if gname == name:
            return digit
    char = toUnicode(name)
    return char if len(char) == 1 else None


def glyph_unicode(name: str) -> int | None:
    ch = glyph_char(name)
    if ch is None:
        return None
    return ord(ch)


def load_locked(path: Path) -> set[str]:
    if not path.exists():
        return set()
    names: set[str] = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            names.add(line)
    return names


def save_locked(path: Path, names: set[str]) -> None:
    path.write_text(
        "".join(f"{n}\n" for n in sorted(names)) or "",
        encoding="utf-8",
    )


_SAFE_NAME = re.compile(r"^[A-Za-z][A-Za-z0-9_.]*$")


def assert_safe_glyph_name(name: str) -> None:
    if not _SAFE_NAME.match(name) and name not in ASCII_GLYPHS:
        # allow single letters and known names; reject path tricks
        if not (len(name) == 1 and name.isalpha()):
            raise ValueError(f"unsafe glyph name: {name!r}")


def glyph_filename(name: str) -> str:
    """Case-insensitive-safe filename for a glyph (UFO-style underscore after capitals).

    On APFS/HFS default volumes, ``Aacute.json`` and ``aacute.json`` collide, so
    ``Aacute`` is stored as ``A_acute.json`` and ``A`` as ``A_.json``.
    """
    return re.sub(r"([A-Z])", r"\1_", name) + ".json"


def glyph_name_from_path(path: Path) -> str:
    return re.sub(r"([A-Z])_", r"\1", path.stem)
